/*Write a C program to calculate area of a rectangle:
  a)Using hard coded values.
  */

#include <stdio.h>

int main()
{

    int length = 52;           // Hard coded value for length
    int width = 72;            // Hard coded value for width
    int area = length * width; // Calculate area
    printf("Area of rectangle: %d\n", area);
    return 0;
}